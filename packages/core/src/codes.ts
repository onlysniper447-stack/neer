const reasons = new WeakMap<CheckResult, CheckCode>();

/** Attach internal identity without changing JSON, object keys, receipts or hashes. */
export function identifyCheck(check: CheckResult, code: CheckCode): CheckResult {
  reasons.set(check, code);
  return check;
}

export function checkCode(check: CheckResult): CheckCode | undefined {
  return reasons.get(check);
}
